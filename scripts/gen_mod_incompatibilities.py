#!/usr/bin/env python3
"""
Generate src/data/mod-incompatibilities.ts from wiki.warframe.com Module:Mods/data
(cached at scripts/_wiki_mods_data.lua; refresh with scripts/sync_mods_from_wiki.py).

Each wiki mod entry may carry `Incompatible = { "Mod A", ... }`: the mods the game refuses to
equip alongside it on the same item (Primed / Umbral / Archon / Amalgam / Galvanized /
Sacrificial variants, corrupted pairs such as Point Strike + Critical Delay, the Archon set
Hatred/Anguish trios, ...). This script turns those lists into symmetric pairs of Voidforge
mod ids, matched by display name (case-insensitive). Names the catalog doesn't have
(Flawed mods, Conclave-only variants not in Voidforge) are skipped and reported.

Usage: python3 scripts/gen_mod_incompatibilities.py [--report out.json]
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LUA = ROOT / "scripts/_wiki_mods_data.lua"
MODS_TS = ROOT / "src/data/mods.ts"
OUT = ROOT / "src/data/mod-incompatibilities.ts"

ENTRY = re.compile(r'^\t\t(?:\["((?:[^"\\]|\\.)+)"\]|([A-Za-z_][A-Za-z0-9_]*)) = \{\n(.*?)^\t\t\}', re.S | re.M)


def wiki_entries():
    src = LUA.read_text(encoding="utf-8").replace("\r\n", "\n")
    out = []
    for m in ENTRY.finditer(src):
        body = m.group(3)
        name = re.search(r'^\t\t\tName = "((?:[^"\\]|\\.)*)"', body, re.M)
        inc = re.search(r'^\t\t\tIncompatible = \{([^}]*)\}', body, re.M)
        out.append({
            "name": (name.group(1) if name else (m.group(1) or m.group(2))).replace('\\"', '"'),
            "incompatible": [s.replace('\\"', '"') for s in re.findall(r'"((?:[^"\\]|\\.)*)"', inc.group(1))] if inc else [],
        })
    return out


def catalog():
    src = MODS_TS.read_text(encoding="utf-8")
    by_name = {}
    for mod_id, name in re.findall(r'\{\s*"id": "([^"]+)",\s*"name": "((?:[^"\\]|\\.)+)"', src):
        by_name.setdefault(name.replace('\\"', '"').lower(), []).append(mod_id)
    return by_name


def main():
    entries = wiki_entries()
    by_name = catalog()
    pairs, skipped, ambiguous = set(), set(), set()

    def ids_for(name):
        ids = by_name.get(name.lower())
        if not ids:
            skipped.add(name)
            return []
        if len(ids) > 1:
            ambiguous.add(name)
            return []
        return ids

    for e in entries:
        if not e["incompatible"]:
            continue
        for a in ids_for(e["name"]):
            for other in e["incompatible"]:
                for b in ids_for(other):
                    if a != b:
                        pairs.add(tuple(sorted((a, b))))

    lines = [
        "// Generated by scripts/gen_mod_incompatibilities.py from wiki.warframe.com Module:Mods/data",
        "// (`Incompatible` lists, cached in scripts/_wiki_mods_data.lua). Do not edit by hand.",
        "// Each pair is two Voidforge mod ids the game won't equip together on one item.",
        "export const WIKI_INCOMPATIBLE_MOD_PAIRS: readonly (readonly [string, string])[] = [",
    ]
    for a, b in sorted(pairs):
        lines.append(f"  [{json.dumps(a)}, {json.dumps(b)}],")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    report = {
        "wikiEntries": len(entries),
        "entriesWithIncompatible": sum(1 for e in entries if e["incompatible"]),
        "pairs": len(pairs),
        "skippedNames": sorted(skipped),
        "ambiguousNames": sorted(ambiguous),
    }
    if "--report" in sys.argv:
        Path(sys.argv[sys.argv.index("--report") + 1]).write_text(json.dumps(report, indent=1))
    print(json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in report.items()}))


if __name__ == "__main__":
    main()
