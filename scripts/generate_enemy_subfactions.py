#!/usr/bin/env python3
"""
Generate src/data/enemy-subfactions.ts: enemy id → wiki damage sub-faction
(Kuva Grineer, Corpus Amalgam, Infested Deimos) for the Update 36 damage type
modifier table. Reuses generate_enemies_catalog.py parsing so ids match enemies.ts,
without regenerating enemies.ts itself.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import generate_enemies_catalog as g  # noqa: E402

SUBFACTIONS = {"kuva grineer": "Kuva Grineer", "corpus amalgam": "Corpus Amalgam", "infested deimos": "Infested Deimos"}
OUT = g.ROOT / "src" / "data" / "enemy-subfactions.ts"


def main() -> None:
    raw: list[dict] = []
    for p in sorted(g.DUMP_DIR.glob("*.lua")):
        t = p.read_text(encoding="utf-8", errors="ignore")
        if t.lstrip().startswith("return"):
            raw += g.extract_entries(t)
    extra = g.DUMP_DIR / "extra.json"
    if extra.exists():
        raw += json.loads(extra.read_text(encoding="utf-8"))
    by: dict[str, dict] = {}
    for e in raw:  # same id / dedupe rules as build_catalog()
        name = e["name"]
        if g.SKIP_NAME_RE.search(name) and e.get("faction_raw", "").lower() in ("prey", "predator", ""):
            continue
        f = g.normalize_faction(e.get("faction_raw"), name, e.get("faction_override"))
        if not f or f.lower() in ("prey", "predator"):
            continue
        h = int(e["health"])
        disp = g.paper_suffix(name, e.get("wiki_type") or "", h)
        eid = g.slug(name)
        if eid in by and by[eid]["name"] != disp:
            eid = g.slug(f"{f}_{name}")
        if eid in by and h <= by[eid]["h"]:
            continue
        by[eid] = {"name": disp, "h": h, "raw": (e.get("faction_raw") or "").strip().lower()}
    current = re.findall(r'\{ id: "([^"]+)"', (g.ROOT / "src" / "data" / "enemies.ts").read_text(encoding="utf-8"))
    rows = sorted((i, SUBFACTIONS[by[i]["raw"]]) for i in current if i in by and by[i]["raw"] in SUBFACTIONS)
    lines = [
        "/**",
        " * Enemy id → wiki damage sub-faction (Update 36 damage type modifiers).",
        " * Generated by scripts/generate_enemy_subfactions.py from scripts/wiki-enemies/ (Module:Enemies/data).",
        " */",
        'export type EnemySubfaction = "Kuva Grineer" | "Corpus Amalgam" | "Infested Deimos";',
        "",
        "export const ENEMY_SUBFACTION: Record<string, EnemySubfaction> = {",
        *[f'  "{i}": "{s}",' for i, s in rows],
        "};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
